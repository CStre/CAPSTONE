/**
 * @fileoverview Runtime loader for the Travel photo pool metadata.
 *
 * The pool is NOT bundled into the Lambda — it lives as `photos.json` in the shared
 * `bba-photos` S3 bucket (alongside the image binaries), so the photo set can be
 * regenerated and re-synced without a code deploy. This module fetches it **once per
 * cold start** and caches it in module scope (warm invocations reuse it); local dev
 * reads a `backend/photos.json` file instead of hitting S3.
 *
 * Loading also primes the country signatures (`setCountrySignatures`) so the
 * synchronous `getCountrySignatures()` used in resolvers returns photo-derived
 * signatures. `ensurePool()` is awaited in the GraphQL context (yoga.ts) before any
 * resolver runs. On any failure it degrades to an empty pool + the catalog seed —
 * the app still works, just without cached photos.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GetObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { config } from './config';
import { setCountrySignatures, signaturesFromPool } from './signatures';
import type { CachedPhoto } from './photos.types';

type Pool = Record<string, CachedPhoto[]>;

/** Dev-only path: `backend/photos.json` (generated by `npm run build:photos`; cwd is backend/). */
const LOCAL_PATH = join(process.cwd(), 'photos.json');

let cache: Pool | null = null;
let inflight: Promise<Pool> | null = null;

function fromLocal(): Pool {
  if (!existsSync(LOCAL_PATH)) return {};
  return JSON.parse(readFileSync(LOCAL_PATH, 'utf8')) as Pool;
}

async function fromS3(): Promise<Pool> {
  const s3 = new S3Client({ region: config.awsRegion });
  const res = await s3.send(
    new GetObjectCommand({ Bucket: config.photosBucket, Key: config.photosKey }),
  );
  const body = await res.Body?.transformToString();
  return body ? (JSON.parse(body) as Pool) : {};
}

async function load(): Promise<Pool> {
  // Tests stay hermetic — never pick up a generated photos.json on disk.
  if (process.env.NODE_ENV === 'test') return {};
  try {
    const pool = config.isLocal ? fromLocal() : await fromS3();
    // Prime photo-derived signatures; leave the catalog seed if the pool is empty.
    if (Object.keys(pool).length > 0) setCountrySignatures(signaturesFromPool(pool));
    return pool;
  } catch (err) {
    console.error(`photo pool load failed — degrading to seed: ${(err as Error).message}`);
    return {};
  }
}

/** Load the pool once (memoized) and prime signatures. Safe to call on every request. */
export async function ensurePool(): Promise<Pool> {
  if (cache) return cache;
  inflight ??= load();
  cache = await inflight;
  return cache;
}

/** The already-loaded pool, or `{}` if `ensurePool` has not resolved yet. */
export function loadedPool(): Pool {
  return cache ?? {};
}

/** Test hook — reset the module cache between cases. */
export function resetPoolCache(): void {
  cache = null;
  inflight = null;
}
